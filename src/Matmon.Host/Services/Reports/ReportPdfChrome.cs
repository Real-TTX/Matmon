using Matmon.Core.Domain;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Matmon.Host.Services.Reports;

/// <summary>
/// The branded frame every Matmon PDF shares - the audit report and the availability report: the title in the managing
/// partner's colour, its logo top right, "Managed by", slogan and support link, the rule in its second colour, and a
/// footer crediting a white-label product name ("powered by Matmon" stays). Every colour and link is re-validated here
/// (#RRGGBB, absolute http/https), and the logo is only drawn when its bytes are PNG or JPEG - QuestPDF is raster-only
/// and an SVG would throw at GeneratePdf, taking the whole report down.
/// </summary>
public static class ReportPdfChrome
{
    public const string DefaultAccent = "#1D4ED8";

    public static string Accent(SummaryReportBranding? branding) =>
        BrandingSafety.SafeHexColor(branding?.BrandColor) ?? DefaultAccent;

    /// <summary>The section headings: the partner's second colour, else near-black.</summary>
    public static string SectionColor(SummaryReportBranding? branding) =>
        BrandingSafety.SafeHexColor(branding?.SecondaryColor) ?? Colors.Grey.Darken4;

    /// <summary>The header: title, the lines under it (scope, period ...), the partner block, the logo, the rule.</summary>
    public static void Header(IContainer container, string title, IReadOnlyList<string> lines, SummaryReportBranding? branding, bool full = true)
    {
        var accent = Accent(branding);
        var contactUrl = BrandingSafety.SafeContactUrl(branding?.ContactUrl);

        container.Column(outer =>
        {
            outer.Item().Row(row =>
            {
                row.RelativeItem().Column(column =>
                {
                    column.Item().Text(title).FontSize(full ? 20 : 13).Bold().FontColor(accent);
                    foreach (var (line, index) in lines.Select((line, index) => (line, index)))
                    {
                        if (string.IsNullOrWhiteSpace(line))
                        {
                            continue;
                        }

                        var text = column.Item().Text(line);
                        if (index == 0)
                        {
                            text.FontSize(full ? 12 : 9).SemiBold();
                        }
                        else
                        {
                            text.FontSize(9).FontColor(Colors.Grey.Darken1);
                        }
                    }

                    if (full)
                    {
                        if (branding?.PartnerName is { Length: > 0 } partnerName)
                        {
                            column.Item().PaddingTop(2).Text($"Managed by {partnerName}").FontSize(9).FontColor(Colors.Grey.Darken1);
                        }

                        if (branding?.Slogan is { Length: > 0 } slogan)
                        {
                            column.Item().Text(slogan).FontSize(9).Italic().FontColor(Colors.Grey.Darken1);
                        }

                        if (contactUrl is not null)
                        {
                            column.Item().Text(text => text.Hyperlink(contactUrl, contactUrl).FontSize(9).FontColor(accent));
                        }
                    }
                });

                if (branding?.LogoPng is { Length: > 0 } logo && IsRasterImage(logo))
                {
                    // A fixed box (width AND height), aspect kept - FitHeight alone lets a wide logo overflow and throw.
                    row.ConstantItem(full ? 170 : 110).AlignTop().AlignRight().Height(full ? 46 : 26).Image(logo).FitArea();
                }
                else if (MatmonLogoSvg is { } matmonLogo)
                {
                    // No partner, or a partner without a (raster) logo: the report carries Matmon's own. The SVG draws its
                    // letters as geometry, so no font is needed; 552 x 104 is its viewBox.
                    var width = full ? 150f : 100f;
                    row.ConstantItem(width).AlignTop().AlignRight().Width(width).Height(width * 104 / 552).Svg(matmonLogo);
                }
            });

            var secondary = BrandingSafety.SafeHexColor(branding?.SecondaryColor);
            outer.Item().PaddingTop(6).LineHorizontal(secondary is null ? 1 : 2).LineColor(secondary ?? Colors.Grey.Lighten2);
        });
    }

    /// <summary>The footer: who made it (the white-label product, "powered by Matmon"), an optional middle text, page n / m.</summary>
    public static void Footer(IContainer container, SummaryReportBranding? branding, string? middle = null)
    {
        var generatedBy = branding?.ProductName is { Length: > 0 } product
            ? $"Generated by {product} · powered by Matmon"
            : "Generated by Matmon";

        container.Row(row =>
        {
            row.RelativeItem(2).Text(generatedBy).FontSize(8).FontColor(Colors.Grey.Medium);
            if (!string.IsNullOrWhiteSpace(middle))
            {
                row.RelativeItem().AlignCenter().Text(middle).FontSize(8).FontColor(Colors.Grey.Medium);
            }

            row.RelativeItem().AlignRight().Text(text =>
            {
                text.DefaultTextStyle(style => style.FontSize(8).FontColor(Colors.Grey.Medium));
                text.Span("Page ");
                text.CurrentPageNumber();
                text.Span(" / ");
                text.TotalPages();
            });
        });
    }

    /// <summary>The Matmon logo (wwwroot/brand/matmon-logo-horizontal.svg, embedded in the assembly so a PDF built anywhere -
    /// a background job, a test - has it); null when the resource is missing, and the header simply has no logo then.</summary>
    public static string? MatmonLogoSvg { get; } = LoadMatmonLogo();

    private static string? LoadMatmonLogo()
    {
        using var stream = typeof(ReportPdfChrome).Assembly.GetManifestResourceStream("Matmon.Brand.LogoHorizontal.svg");
        if (stream is null)
        {
            return null;
        }

        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    public static bool IsRasterImage(byte[] bytes)
    {
        if (bytes.Length >= 8 &&
            bytes[0] == 0x89 && bytes[1] == 0x50 && bytes[2] == 0x4E && bytes[3] == 0x47 &&
            bytes[4] == 0x0D && bytes[5] == 0x0A && bytes[6] == 0x1A && bytes[7] == 0x0A)
        {
            return true; // PNG
        }

        return bytes.Length >= 3 && bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[2] == 0xFF; // JPEG
    }

    public static string StateColor(SensorState state) => state switch
    {
        SensorState.Critical => Colors.Red.Darken1,
        SensorState.Warning => Colors.Orange.Darken2,
        SensorState.Healthy => Colors.Green.Darken1,
        _ => Colors.Grey.Darken1
    };

    public static void HeaderCell(TableCellDescriptor header, string text, bool alignRight = false)
    {
        var cell = header.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten1).PaddingVertical(4).PaddingHorizontal(4);
        (alignRight ? cell.AlignRight() : cell).Text(text).FontSize(8.5f).SemiBold().FontColor(Colors.Grey.Darken2);
    }

    public static IContainer BodyCell(TableDescriptor table) =>
        table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten3).PaddingVertical(3).PaddingHorizontal(4);
}
